package p002_datatypes;

public class C002_PrimitiveDataTypesExample {

	public static void main(String[] args) {

		byte age = 24;
		short passoutYear = 2024;
		int employeeId = 1001;
		long phoneNumber = 9876543210L;

		float attendance = 95.5f;
		double accountBalance = 50000.75;

		char section = 'A';
		boolean isJavaDeveloper = true;

		System.out.println("Age = " + age);
		System.out.println("Passout Year = " + passoutYear);
		System.out.println("Employee Id = " + employeeId);
		System.out.println("Phone Number = " + phoneNumber);
		System.out.println("Attendance = " + attendance);
		System.out.println("Account Balance = " + accountBalance);
		System.out.println("Section = " + section);
		System.out.println("Is Java Developer = " + isJavaDeveloper);
	}
}