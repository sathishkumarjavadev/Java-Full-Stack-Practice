package p004_loops;

public class C003_ForLoop_Task1 {
public static void main(String[] args) {
	for(int i=1;i<=5;i++) {
		System.out.println(i);
	}
	for(int i=10;i>0;i--)
	{
		System.out.println(i);
	}
	for(int i=1;i<=20;i++) {
		if(i%2==0) {
			System.out.println(i);
		}	
	}
	for(int i=1;i<=5;i++)
	{
		System.out.println("*");
	}
	for(int i = 1; i <= 3; i++) {
	    System.out.println(i);//output is 1,2,3
	}
}
}
